#!/usr/bin/env node
// Writes SupportSlot/Config/Secrets.xcconfig (gitignored) from the Supabase
// values in .env.local, so the app and the scripts point at the same project.
//
//   node scripts/make-app-config.mjs
//
// Only the project host and the PUBLIC anon key go into the app. The
// service-role key is never written anywhere near it. It refuses the retired
// project (see scripts/lib/live.mjs).

import fs from "fs";
import { loadEnv, projectRef } from "./lib/live.mjs";

const env = loadEnv({ needService: false });
const host = new URL(env.url).host;
const out = new URL("../SupportSlot/Config/Secrets.xcconfig", import.meta.url);
fs.writeFileSync(
  out,
  `// Generated by scripts/make-app-config.mjs from .env.local — gitignored, do not commit.\nSUPABASE_HOST = ${host}\nSUPABASE_ANON_KEY = ${env.anon}\n`
);
console.log(`Wrote SupportSlot/Config/Secrets.xcconfig for project ${projectRef(env.url)}`);
