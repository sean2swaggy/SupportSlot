#!/usr/bin/env node
// Writes SupportSlot/Config/Secrets.xcconfig (gitignored) from the Supabase
// values in .env.local, so the app and the scripts point at the same project.
//
//   node scripts/make-app-config.mjs
//
// Only the project host and the PUBLIC anon key go into the app. The
// service-role key is never written anywhere near it.

import fs from "fs";

const env = fs.readFileSync(new URL("../.env.local", import.meta.url), "utf8");
const get = (k) => env.match(new RegExp(`^${k}=(.*)$`, "m"))?.[1]?.trim() ?? "";
const url = get("NEXT_PUBLIC_SUPABASE_URL");
const anon = get("NEXT_PUBLIC_SUPABASE_ANON_KEY");
if (!url || !anon) {
  console.error("NEXT_PUBLIC_SUPABASE_URL and NEXT_PUBLIC_SUPABASE_ANON_KEY must be set in .env.local");
  process.exit(1);
}
const host = new URL(url).host;
const out = new URL("../SupportSlot/Config/Secrets.xcconfig", import.meta.url);
fs.writeFileSync(
  out,
  `// Generated by scripts/make-app-config.mjs from .env.local — gitignored, do not commit.\nSUPABASE_HOST = ${host}\nSUPABASE_ANON_KEY = ${anon}\n`
);
console.log(`Wrote SupportSlot/Config/Secrets.xcconfig for project ${host.split(".")[0]}`);
